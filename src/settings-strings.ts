/** The settings page's table for the interface language `lang`. */
export function settingsText(lang: UiLanguage): SettingsText {
  return lang === "en" ? SETTINGS_TEXT_EN : SETTINGS_TEXT;
}

/** `template` with each `{name}` replaced by `values[name]`. */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
}
