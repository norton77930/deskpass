async function emptyView() {
  const root = join(repoRoot(), "test-tmp");
  await mkdir(root, { recursive: true });
  const dir = await mkdtemp(join(root, "all-apps-"));
  const mac: GrantMac = async () => ({ macs: [], key_state: "ok" });
  const view = await new GrantStore({ dir, record: async () => undefined }).current(mac);
  return { view, done: () => rm(dir, { recursive: true, force: true }) };
}

